import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=path.resolve(process.env.PREVIEW_ROOT||'_site','arena2d');
const {modules}=JSON.parse(fs.readFileSync(path.join(root,'version.json'),'utf8'));
const file=path.join(root,modules,'selector.js');
const src=fs.readFileSync(file,'utf8');
const syntax=spawnSync(process.execPath,['--check',file],{encoding:'utf8'});
assert.equal(syntax.status,0,syntax.stderr);
assert.match(src,/const POR_FILA=4,FILAS=2,PAGE_SIZE=8/);
assert.match(src,/buildPokedexFamilies\(ROSTER,JOHTO_100_ROWS,LEVEL_EVOLUTIONS\)/);
assert.match(src,/this\.order\.slice\(this\.page\*PAGE_SIZE/);
assert.match(src,/this\.families\.membersByRoot\.get\(root\)/);
assert.match(src,/this\.addPortrait\(cas\.img,p\.dex,LW\)/);
assert.match(src,/this\.alElegir\?\.\(p\.id,k\)/);
assert.doesNotMatch(src,/Math\.min\(13,Math\.ceil\(ROSTER\.length/);
assert.ok(fs.existsSync(path.join(root,modules,'torre2/pokedex-families.js')));
assert.ok(fs.existsSync(path.join(root,modules,'torre2/johto-100-data.js')));
assert.ok(fs.existsSync(path.join(root,modules,'torre2/progression.js')));
console.log('PASS_ARENA_PREPARAR_FAMILY_SELECTOR_BUILD',JSON.stringify({modules,pageSize:8,columns:4,rows:2}));

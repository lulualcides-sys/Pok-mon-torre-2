import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const root=path.resolve(process.env.PREVIEW_ROOT||'_site','arena2d');
const version=JSON.parse(fs.readFileSync(path.join(root,'version.json'),'utf8')).modules;
const load=p=>import(pathToFileURL(path.join(root,version,p)));
const {MART_ITEMS,GYM_TM_REWARDS}=await load('torre2/route-data.js');
const core=await load('torre2/campaign-core.js');
const pool=await load('torre2/move-pool.js');
const {createPartyMatch}=await load('torre2/party-battle.js');
const {TORRE2_TOXIC_FORMS}=await load('torre2/toxic-fx.js');
const {TORRE2_FORMS}=await load('torre2/signature-fx.js');
const store=new Map();
globalThis.localStorage={getItem:k=>store.get(k)??null,
 setItem:(k,v)=>store.set(k,String(v)),removeItem:k=>store.delete(k)};
const toxic=pool.TEST_LIBRARY.filter(m=>m.id==='toxic');
assert.equal(toxic.length,1,'One canonical Toxic move in the entire game');
assert.equal(toxic[0].approved,false,'New Toxic VFX remains review pending');
assert.equal(toxic[0].poder,0);
assert.equal(toxic[0].dano,0);
assert.equal(toxic[0].precisao,85);
assert.equal(typeof TORRE2_FORMS[toxic[0].forma],'function',
 'Toxic has a registered Phaser renderer');
assert.equal(TORRE2_FORMS[toxic[0].forma],TORRE2_TOXIC_FORMS[toxic[0].forma]);
assert.equal(GYM_TM_REWARDS[4],'tm-toxic','Koga awards TM06');
const tm=MART_ITEMS.find(i=>i.id==='tm-toxic');
assert.equal(tm.move,'Toxic');
assert.ok(tm.compatible.includes('bulbasaur'),'Canonical FRLG Bulbasaur compatibility');
assert.ok(!tm.compatible.includes('magikarp'),'No universal TM teaching');
const koga=core.createCampaign('bulbasaur');koga.stage=4;
koga.trainer=core.TRAINERS_PER_GYM(4);
const kogaOpponent=core.currentOpponent(koga);
assert.ok(kogaOpponent?.leader,'Stage 4 must be the actual Koga gym leader');
const kogaParty=createPartyMatch(koga,kogaOpponent,false);
assert.deepEqual(kogaParty.foes.map(x=>x.id),['koffing','muk','koffing','weezing']);
for(const foe of kogaParty.foes.filter(x=>['muk','weezing'].includes(x.id))){
 assert.equal(foe.loadout.q.nombre,'Toxic','Koga '+foe.id+' should use Toxic in real fight');
 assert.equal(foe.loadout.q.forma,'torre2_toxic');
}
const state=core.createCampaign('bulbasaur');
state.stage=4;state.trainer=core.TRAINERS_PER_GYM(4);
const reward=core.resolveBattle(state,true);
assert.equal(reward.won,true);assert.equal(state.stage,5);
assert.equal(state.inventory.tms.filter(x=>x==='tm-toxic').length,1);
assert.equal(state.gymTMClaims.filter(x=>x==='tm-toxic').length,1);
assert.equal(core.grantGymTM(state,4).claimed,false,'Do not repeat reward');
const taught=core.teachTM(state,'tm-toxic',0);
assert.equal(taught.ok,true);
assert.equal(state.inventory.tms.includes('tm-toxic'),false,'TM consumed after teaching');
assert.ok(pool.availableMoves(state.team[0]).some(x=>x.id==='toxic'));
assert.equal(core.teachTM(state,'tm-toxic',0).ok,false,'Cannot consume twice');
const restored=core.readCampaign();
assert.ok(restored.team[0].tmMoves.includes('Toxic'),'Persist learned move');
assert.equal(restored.gymTMClaims.filter(x=>x==='tm-toxic').length,1);
const legacy=core.createCampaign('bulbasaur');legacy.stage=5;
legacy.badges=['Alma'];legacy.gymTMClaims=[];legacy.inventory.tms=[];
core.saveCampaign(legacy);
const migrated=core.readCampaign();
assert.equal(migrated.inventory.tms.filter(x=>x==='tm-toxic').length,1,
 'Legacy Koga victory restored exactly once');
assert.deepEqual(core.readCampaign(),migrated);
console.log('PASS Toxic TM06 Koga one-time reward, real renderer, Gen III compatibility, save, and migration');

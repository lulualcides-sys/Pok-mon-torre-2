/* Mewtwo Johto laboratory: 18 original, additive Phaser Graphics VFX.
 * Uses P2-style timed action + native real-contact receiving and T2 particle FX.
 * This is a battle prototype, not complete Gen II status/item/IV parity.
 */
import * as vfx from "../vfx.js";
import {JOHTO_18} from "./johto-lab-catalog.js";
import {JOHTO_P2_TEXTURES,JOHTO_PIXEL_PALETTES,JOHTO_PIXEL_FRAMES,stampJohto} from "./johto-lab-pixelart.js";
const tones={
 "triple-kick":[0xedb555,0xfff0b9],"thief":[0x715298,0xd5b8ed],
 "snore":[0x6ed0de,0xc9f8ff],"powder-snow":[0x79c6ed,0xf1ffff],
 "octazooka":[0x3b4482,0xb2a1ed],"zap-cannon":[0xe5bc38,0xf9f3b7],
 "false-swipe":[0x75dcb1,0xcafce2],"steel-wing":[0x83a5ba,0xeaf8ff],
 "return":[0xcfac86,0xffe7c7],"present":[0xd84f78,0xffd3a5],
 "frustration":[0xd44b48,0xffb26b],"magnitude":[0xa38958,0xffe3a1],
 "pursuit":[0x5d489c,0xd5cbf7],"vital-throw":[0xd88e4f,0xffebcc],
 "hidden-power":[0x7db8ed,0xf9dafd],"rock-smash":[0xa18d6d,0xffe5bd],
 "whirlpool":[0x2087a9,0xb8f1ff],"beat-up":[0x786080,0xf2e1fb]
};
const projectile=new Set(["snow","ink","electric","gift","orb","sound","vortex"]);
const adjacent=new Set(["kick","slash","wing","dash","throw","rock"]);
const near=(a,b,r)=>Math.hypot(a.x-b.x,a.y-b.y)<=r;
/* Native Poké Arena 2D's p-* texture atlas is generated by original
 * vfx.js. Overlay with 18 individual hand-authored pixel sprites at integer
 * coordinates, following the approved 2x2 tile method of batch24/pixels.js.
 * There are NO outline circles, vector arcs, glow ellipses or generic beams.
 */
function nativeP2(e,id){
 const textures=JOHTO_P2_TEXTURES[id]||[];
 return textures.map((name,index)=>{
  if(!e.textures.exists(name))return null;
  const img=e.add.image(0,0,name);
  img.setDepth(1531+index);
  img.setScale(index===0?3:2);
  img.setAlpha(index===0?.98:.83);
  return img;
 }).filter(Boolean);
}
function paintNativeSprites(imgs,id,x,y,age,duration,r,l){
 const frame=Math.min(JOHTO_PIXEL_FRAMES-1,Math.floor(age/duration*JOHTO_PIXEL_FRAMES));
 const target={x:Math.round(r.x),y:Math.round(r.y-r.alto*.5)};
 const bob=(frame%4-2)*2;
 const orbit=frame*Math.PI/6;
 const xy={x:Math.round(x),y:Math.round(y)};
 for(let i=0;i<imgs.length;i++){
  const img=imgs[i];
  const isOrb=id==='hidden-power'||id==='zap-cannon'||id==='powder-snow';
  const splash=id==='magnitude'||id==='rock-smash'||id==='whirlpool';
  const center=splash&&age>duration*.25?target:xy;
  const off=i?Math.round(Math.cos(orbit)*21):0;
  const offY=i?Math.round(Math.sin(orbit)*15):0;
  img.setPosition(center.x+off,center.y+offY+(isOrb?bob:0));
  img.setAlpha(Math.max(.25,(i?.75:1)*(1-Math.max(0,age/duration-.75)*2)));
  if(isOrb)img.setAngle((frame%4)*90);
  else if(id==='steel-wing'||id==='false-swipe'||id==='thief')img.setAngle(i?90:frame%3===0?-90:0);
  else img.setAngle(0);
 }
}
function pixelShards(g,id,x,y,age,phase,scale=2){
 const frame=Math.floor(phase*JOHTO_PIXEL_FRAMES);
 const [base,shadow,body,light,white]=tones[id]?
  [0x17192d,...tones[id],...tones[id]]:[0x17192d,0x353044,0x9ba4c0,0xdde8ff,0xffffff];
 const centers=8,reach=6+phase*29;
 for(let n=0;n<centers;n++){
  const a=n*2.39996+(frame%3)*.12;
  const drift=n%3===0?1.22:1;
  const xx=Math.round(x+Math.cos(a)*reach*drift);
  const yy=Math.round(y+Math.sin(a)*reach*.67);
  const size=frame>7?1:n%3===0?3:2;
  g.fillStyle(n%4===0?white:n%2===0?light:body,Math.max(.15,1-phase*.85));
  g.fillRect(xx,yy,size*scale/2,size*scale/2);
 }
}
// Crisp stepped pixel clusters from an authored trajectory, never a vector
// stroke. The native P2 renderer displays every cell at integer coordinates.
function tileRoute(g,x1,y1,x2,y2,ink,highlight,weight=2){
 const dx=x2-x1,dy=y2-y1;
 const parts=Math.max(1,Math.ceil(Math.max(Math.abs(dx),Math.abs(dy))/4));
 for(let i=0;i<=parts;i++){
  const px=Math.round(x1+dx*i/parts),py=Math.round(y1+dy*i/parts);
  g.fillStyle(ink,1).fillRect(px-1,py-1,weight+2,weight+2);
  g.fillStyle(highlight,.96).fillRect(px,py,weight,weight);
 }
}
function signatureFrames(g,id,age,duration,x,y,r,l,frame,alpha){
 const pal=JOHTO_PIXEL_PALETTES[id];if(!pal)return;
 const phase=Math.min(1,age/duration);
 const tx=Math.round(r.x),ty=Math.round(r.y-r.alto*.5);
 const sx=Math.round(l.x),sy=Math.round(l.y-l.alto*.5);
 const px=Math.round(x),py=Math.round(y);
 const stamp=(cx,cy,scale=1,flip=false,opacity=alpha)=>stampJohto(g,id,cx,cy,frame,scale,opacity,flip);
 if(id==='zap-cannon'){
  const path=[
   {x:sx,y:sy},{x:sx+24,y:sy-12},{x:sx+43,y:sy+9},
   {x:px-28,y:py-15},{x:px-9,y:py+10},{x:px,y:py}
  ];
  for(let i=1;i<path.length;i++){
   const a=path[i-1],b=path[i];
   tileRoute(g,a.x,a.y,b.x,b.y,pal[1],pal[4],i%2?2:3);
  }
  for(const [dx,dy] of [[-22,-18],[12,-24],[22,12],[-7,26]]){
   tileRoute(g,px,py,px+dx,py+dy,pal[1],pal[3],2);
   g.fillStyle(pal[4]).fillRect(px+dx-2,py+dy-2,5,5);
  }
 }else if(id==='whirlpool'){
  // Two crossing water spirals embrace the real opponent, rather than
  // a generic expanding circle in front of the caster.
  for(let n=0;n<9;n++){
   const a=n*.86+age*9,radius=12+4*(n%4);
   const yy=ty-22+(n%5)*9,xx=tx+Math.round(Math.cos(a)*radius);
   stamp(xx,yy,1,n%2===0,alpha*.85);
   g.fillStyle(pal[4],.85).fillRect(xx+Math.round(Math.sin(a)*7),yy-3,3,3);
  }
  for(const n of [-1,0,1]){
   tileRoute(g,tx-26,ty+n*12,tx+26,ty-8+n*10,pal[1],pal[n===0?4:3],2);
  }
 }else if(id==='powder-snow'){
  for(let n=0;n<9;n++){
   const t=n/9,a=t*2.2+age*5;
   stamp(Math.round(sx+(px-sx)*t+Math.sin(a)*18),
    Math.round(sy+(py-sy)*t+Math.cos(a*1.3)*20),1,n%2===0,alpha*.72);
  }
 }else if(id==='octazooka'){
  for(let n=0;n<7;n++){
   const a=n*2.4+age*3,dist=10+phase*27;
   stamp(px+Math.round(Math.cos(a)*dist),py+Math.round(Math.sin(a)*dist),1,n%2===0,.8*alpha);
  }
 }else if(id==='false-swipe'||id==='steel-wing'){
  const yoff=id==='steel-wing'?20:9;
  for(const flip of [false,true]){
   stamp(tx+(flip?-12:12),ty+(flip?yoff:-yoff),2,flip,alpha*.85);
  }
  const cutX=tx+(frame%3-1)*9;
  tileRoute(g,cutX-25,ty-24,cutX+24,ty+23,pal[0],pal[4],2);
  if(id==='steel-wing')tileRoute(g,cutX+23,ty-23,cutX-20,ty+17,pal[1],pal[3],2);
 }else if(id==='rock-smash'||id==='magnitude'){
  const ground=Math.round(r.y-5);
  const span=id==='magnitude'?70:38;
  for(let n=-2;n<=2;n++){
   const xx=tx+n*(span/2)|0;
   tileRoute(g,xx-9,ground,xx+7,ground-8-(n%2)*6,pal[0],pal[3],2);
   stamp(xx+Math.round(Math.sin(frame+n)*7),ground-11,1,n%2===0,.7*alpha);
  }
 }else if(id==='triple-kick'||id==='beat-up'){
  const count=id==='triple-kick'?3:5;
  for(let n=0;n<count;n++){
   const t=n*(id==='triple-kick'?.17:.11),delta=age-t;
   if(delta<0||delta>.22)continue;
   stamp(tx+Math.round(Math.cos(n*2.2)*24),
    ty+Math.round(Math.sin(n*2.2)*19),2,n%2===0,alpha);
  }
 }else if(id==='thief'||id==='pursuit'){
  for(let n=0;n<4;n++){
   const t=Math.max(0,phase-n*.13);
   stamp(Math.round(sx+(tx-sx)*t),Math.round(sy+(ty-sy)*t)-n*5,
    1,n%2===0,alpha*.7);
  }
 }else if(id==='snore'){
  for(let n=0;n<4;n++){
   stamp(sx+n*21,sy-14-n*19-Math.round(age*14),1,n%2===0,alpha*.7);
  }
 }else if(id==='hidden-power'){
  for(let n=0;n<6;n++){
   const a=n*Math.PI/3+age*7;
   const rad=30-Math.min(22,phase*20);
   stamp(sx+Math.round(Math.cos(a)*rad),sy+Math.round(Math.sin(a)*rad),1,n%2===0,alpha*.72);
  }
 }else if(id==='vital-throw'||id==='frustration'){
  for(let n=0;n<5;n++){
   const t=n/5;
   stamp(sx+Math.round((tx-sx)*t),sy+Math.round((ty-sy)*t)+((n%2)*12-6),
    1,n%2===0,alpha*.7);
  }
 }else if(id==='return'||id==='present'){
  for(let n=0;n<5;n++){
   const t=n/5;
   stamp(Math.round(sx+(tx-sx)*t),Math.round(sy+(ty-sy)*t-Math.sin(t*Math.PI)*20),
    1,n%2===0,alpha*.6);
  }
 }
}
function artwork(g,id,style,x,y,age,duration,r,l){
 g.clear();
 const phase=Math.min(.999,Math.max(0,age/duration)),frame=Math.floor(phase*JOHTO_PIXEL_FRAMES);
 // Eight-bit authored center silhouettes: 12 timed poses + impact debris.
 const x0=Math.round(x),y0=Math.round(y);
 const isLarge=['zap-cannon','magnitude','whirlpool','vital-throw','rock-smash'].includes(id);
 const scale=isLarge?3:2;
 const tail=phase>.78?Math.max(.15,(1-phase)/.22):1;
 stampJohto(g,id,x0,y0,frame,scale,tail,frame%4===3);
 if(id==='powder-snow'||id==='octazooka'||id==='hidden-power'){
  for(let n=0;n<4;n++){
   const theta=n*Math.PI*.5+age*3.5,radius=12+phase*21;
   stampJohto(g,id,Math.round(x0+Math.cos(theta)*radius),
    Math.round(y0+Math.sin(theta)*radius*.72),frame+n,1,tail*.55,n%2===1);
  }
 }else if(id==='snore'){
  for(let n=0;n<3;n++)stampJohto(g,id,
   x0-23+n*19,y0+14-n*10-Math.round(age*25),frame+n,1,.85-n*.2);
 }else if(id==='triple-kick'||id==='beat-up'){
  const blows=id==='triple-kick'?3:5;
  for(let n=0;n<blows;n++){
   if(age<n*.12||age>n*.12+.27)continue;
   stampJohto(g,id,x0+Math.round(Math.cos(n*2.7)*23),
    y0+Math.round(Math.sin(n*2.7)*15),frame+n,2,tail*.8,n%2===0);
  }
 }else if(id==='whirlpool'){
  for(let n=0;n<4;n++){
   const theta=n*Math.PI*.5+age*9,radius=13+n*7;
   stampJohto(g,id,Math.round(r.x+Math.cos(theta)*radius),
    Math.round(r.y-r.alto*.5+Math.sin(theta)*radius*.6),frame+n,1,tail*.65);
  }
 }else if(id==='magnitude'){
  for(let n=0;n<5;n++){
   const xx=Math.round(l.x+(n-2)*30);
   stampJohto(g,id,xx,Math.round(r.y-5+n%2*5),
    frame+n,n%2===0?2:1,tail*.75,n%2===1);
  }
 }else if(id==='zap-cannon'||id==='frustration'||id==='steel-wing'){
  // Three stepped inked strikes in the ORIGINAL pixel-grid style.
  for(let n=0;n<3;n++)stampJohto(g,id,
   x0+(n-1)*16,y0+(n%2?9:-8),frame+n,1,tail*.6,n%2===0);
 }
 signatureFrames(g,id,age,duration,x0,y0,r,l,frame,tail);
 if(phase>.24)pixelShards(g,id,x0,y0,age,(phase-.24)/.76);
}
function cast(l,h,extra){
 if(!l?.escena?.datos?.johtoLab||!l.rival)return false;
 if(h.id==="snore"&&!l.est?.dormido)return false;
 const e=l.escena,r=l.rival,angle=Math.atan2(l.ay-l.y,l.ax-l.x),dx=Math.cos(angle),dy=Math.sin(angle);
 const style=h.style,palette=tones[h.id];if(!palette)return false;
 const g=e.add.graphics().setDepth(1520);
 const nativeSprites=nativeP2(e,h.id);
 const sx=l.x+dx*12,sy=l.y-l.alto*.5+dy*8;
 const beam=projectile.has(style),melee=adjacent.has(style);
 const duration=style==="vortex"?1.65:style==="quake"?1.05:beam?1.1:.75;
 const windows=h.id==="triple-kick"?[.17,.34,.51]:
  h.id==="beat-up"?[.12,.23,.34,.45,.56]:
  h.id==="whirlpool"?[.4,.7,1,1.3]:[.31];
 let age=0,hits=0,stopped=false;
 l.animar(h.anim||"Attack",.53,.13);
 l.accion={hasta:l.t+.38,angulo:angle,lento:.65};
 const receiver=(x,y)=>{
  const center={x:r.x,y:r.y-r.alto*.5};
  const range=style==="quake"?160:style==="vortex"?78:
   style==="sound"?120:melee?Math.max(30,h.alcance):27;
  return near({x,y},center,range+Math.max(3,r.alto*.2));
 };
 const hit=()=>{
  if(r.ko||stopped)return;
  if(Math.random()>h.precisao/100){if(h.id==="triple-kick")stopped=true;return;}
  let damage=h.dano;
  if(h.id==="triple-kick")damage*=hits+1;
  if(h.id==="beat-up")damage*=.52; // preview until team is modeled
  if(h.id==="magnitude")damage*=[.7,1,1.4,1.8][Math.floor(Math.random()*4)];
  if(h.id==="present"){
   if(Math.random()<.2){r.hp=Math.min(r.hpMax,r.hp+r.hpMax*.25);return;}
   damage*=.7+Math.floor(Math.random()*3)*.45;
  }
  const oldKo=r.ko;
  const outcome=r.recibir(l,{dano:damage,tipo:h.tipo,slot:extra?.slot,
   surge:extra?.surge,dirX:dx,dirY:dy,empuje:18});
  if(h.id==="false-swipe"&&outcome==="golpe"&&(r.ko||r.hp<1)){
   r.hp=Math.max(1,r.hp);r.ko=oldKo;
  }
  if(outcome==="golpe"){
   vfx.rafaga(e,"chispa",r.x,r.y-r.alto*.5,palette[1],8);
   if(h.id==="zap-cannon")r.ponerEstado("paralizado",2.5);
   if(h.id==="whirlpool")r.ponerEstado("lento",.7,{f:.25});
  }
 };
 const fx={update(dt){
  age+=Math.max(0,Math.min(.05,dt||0));
  if(age>=duration){g.destroy();for(const sprite of nativeSprites)sprite.destroy();return false;}
  const travel=Math.min(h.alcance,age*360);
  const x=beam?sx+dx*travel:style==="quake"?l.x+dx*80:melee?l.x+dx*37:r.x;
  const y=beam?sy+dy*travel:style==="quake"?l.y-7:melee?l.y-l.alto*.5+dy*12:r.y-r.alto*.5;
  artwork(g,h.id,style,x,y,age,duration,r,l);
  paintNativeSprites(nativeSprites,h.id,x,y,age,duration,r,l);
  if(hits<windows.length&&age>=windows[hits]){
   if(receiver(x,y))hit();
   hits++; // independent hit windows; only triple-kick stops after miss
  }
  return true;
 },destroy(){g.destroy();for(const sprite of nativeSprites)sprite.destroy();}};
 e.efectos.push(fx);return true;
}

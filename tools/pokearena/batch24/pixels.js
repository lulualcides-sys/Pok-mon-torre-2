export function pixel(g,x,y,c,size=1,alpha=1){g.fillStyle(c,alpha).fillRect(Math.round(x),Math.round(y),size,size)}
export function stamp(g,key,x,y,palette,scale=1,angle=0,alpha=1,flip=false){
 const rows=SHAPES[key],w=Math.max(...rows.map(r=>r.length)),h=rows.length;
 const ca=Math.cos(angle),sa=Math.sin(angle);
 for(let row=0;row<h;row++)for(let col=0;col<rows[row].length;col++){
  const value=rows[row][col];if(value==='.')continue;
  const dx=(col-(w-1)/2)*scale,dy=(flip?-1:1)*(row-(h-1)/2)*scale;
  pixel(g,x+dx*ca-dy*sa,y+dx*sa+dy*ca,palette[Number(value)],scale,alpha);
 }
}
// 12 distinct impact poses: compressed contact, bright split, asymmetric
// fragments, then disappearance. No additional damage from visual debris.
export function impact(g,x,y,palette,age,size=1){
 const f=Math.floor(age*30);if(f>=12)return;
 if(f<4)stamp(g,'p2star',x,y,palette,size*2,0,1-f*.12);
 for(let j=0;j<7;j++){
  const offset=FRAGMENT_POSES[j][f];
  pixel(g,x+offset.x,y+offset.y*.7,
   palette[2+j%3],f<6?2:1,Math.max(0,1-f/12));
 }
}

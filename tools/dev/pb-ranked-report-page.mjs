/**
 * Generates a standalone offline HTML report from public DERIVED metadata.
 * It never loads images, scripts, APIs or third-party code over the network.
 */
export function renderPbAuditHtml(audit) {
  if (!audit || !Array.isArray(audit.moves) || !audit.totals) {
    throw new TypeError('Invalid audit report');
  }
  const safe = JSON.stringify({
    totals:audit.totals,
    moves:audit.moves.map(m=>({
      name:m.name, type:m.type, family:m.family,
      action:m.action, evidence:m.evidenceLevel,
      native:m.nativeSourceMoveIdCurrent,
      protected:m.policyProtectedCurrent,
      categories:m.inferredCategories,
      identifiers:m.staticIdentifiers,
      defaultMove:m.defaultMove, inRoster:m.inPublicRoster,
    }))
  }).replace(/</g,'\\u003c').replace(/>/g,'\\u003e').replace(/&/g,'\\u0026')
    .replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
  const markup = [
    '<!doctype html><html lang="pt-BR"><head>',
    '<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
    '<title>Pokémon Torre 2 — Auditoria dos 283 golpes</title>',
    '<style>',
    ':root{color-scheme:dark;--bg:#101923;--fg:#eaf3fa;--muted:#a9b8c9;--edge:#38516b;--panel:#1a2b3e}',
    '*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,Arial,sans-serif}',
    'main{max-width:1320px;margin:auto;padding:24px 20px 64px}h1{font-size:clamp(25px,4vw,38px);margin:0}',
    'p{color:var(--muted);margin:6px 0 12px}.cards{display:grid;grid-template-columns:repeat(auto-fit,minmax(155px,1fr));gap:10px;margin:20px 0}',
    '.card{background:var(--panel);border:1px solid var(--edge);border-radius:12px;padding:14px}',
    '.card strong{display:block;font-size:28px}.card span{font-size:12px;color:var(--muted)}',
    '.note{border-left:3px solid #64b5d5;background:var(--panel);padding:12px 16px;border-radius:6px;margin:16px 0}',
    '.filters{display:grid;grid-template-columns:minmax(140px,2fr) repeat(3,minmax(125px,1fr));gap:10px;margin:18px 0}',
    'input,select{width:100%;padding:12px;background:#23384e;border:1px solid #56708b;border-radius:8px;color:var(--fg);font:inherit}',
    'input:focus,select:focus{outline:2px solid #a9e0fd;outline-offset:2px}',
    '.tablewrap{overflow:auto;border:1px solid var(--edge);border-radius:12px}table{border-collapse:collapse;min-width:860px;width:100%}',
    'th,td{padding:10px 12px;border-bottom:1px solid #304258;text-align:left;vertical-align:top}',
    'th{position:sticky;top:0;background:#263a51;white-space:nowrap}tr:hover{background:#21364b}',
    '.small{display:block;color:var(--muted);font-size:12px}',
    '.tag{padding:2px 8px;border:1px solid #637e94;border-radius:10px;display:inline-block;font-size:11px}',
    '.tag.protected{color:#edce94;border-color:#a6854e}.tag.low{color:#ffb9b9;border-color:#a06b70}',
    'details{max-width:290px}summary{cursor:pointer;color:#a9e0fd}footer{margin-top:25px;font-size:13px;color:var(--muted)}',
    '@media(max-width:700px){main{padding:15px 10px}.filters{grid-template-columns:1fr 1fr}.filters input{grid-column:span 2}}',
    '</style></head><body><main>',
    '<h1>Auditoria técnica de 283 golpes</h1>',
    '<p>Pesquisa PB Ranked · comparação de nomes com catálogo Poké Arena 2D existente · uso somente leitura</p>',
    '<div class="note"><strong>Limites:</strong> ausência no catálogo de 165 nomes não prova ausência no motor Torre 2. Uso relatado contra bot não comprova quadros de VFX. Os efeitos aprovados permanecem intocáveis. Nenhum sprite externo foi importado.</div>',
    '<section class="cards" id="cards" aria-label="Resumo da pesquisa"></section>',
    '<section><h2>Consultar</h2><div class="filters">',
    '<input type="search" id="query" aria-label="Buscar golpe" placeholder="Nome, tipo ou pista..." autocomplete="off">',
    '<select id="type" aria-label="Filtrar tipo"><option value="">Todos os tipos</option></select>',
    '<select id="action" aria-label="Filtrar ação"><option value="">Todas as ações</option></select>',
    '<select id="evidence" aria-label="Filtrar evidência"><option value="">Toda evidência</option></select>',
    '</div><p id="count" role="status" aria-live="polite"></p></section>',
    '<div class="tablewrap"><table><thead><tr>',
    '<th>Golpe</th><th>Tipo / família</th><th>Recomendação</th><th>Catálogo P2</th><th>Evidência</th><th>Pistas técnicas</th>',
    '</tr></thead><tbody id="moves"></tbody></table></div>',
    '<footer>Relatório gerado offline a partir de metadados públicos. Não modifica o jogo nem valida licenças de ativos.</footer>',
    '</main>',
    '<script id="pb-audit-data" type="application/json">',
    safe,
    '</script>',
    '<script>',
    '(function(){',
    'const payload=JSON.parse(document.getElementById("pb-audit-data").textContent);',
    'const $=id=>document.getElementById(id);',
    'const labels={"preserve-approved":"Preservar aprovado","inspect-existing-source":"Conferir fonte existente","test-default-in-bot":"Testar padrão no bot","test-after-move-edit":"Exige configurar golpe","static-only-nonroster":"Somente metadados","agent-reported":"Uso relatado, sem VFX completo","aggregate-low-confidence":"Relato agregado, confiança baixa","static-only":"Apenas código"};',
    'const label=value=>labels[value]||value||"—";',
    'function el(tag,value,cls){const n=document.createElement(tag);if(value!==undefined)n.textContent=String(value);if(cls)n.className=cls;return n;}',
    'const summary=[["283","Nomes analisados"],[payload.totals.inRoster,"Disponíveis no elenco público"],[payload.totals.reported,"Usos relatados"],[payload.totals.lowConfidence,"Baixa confiança"],[payload.totals.currentNativeMatches,"Também no catálogo P2"],[payload.totals.protected,"Protegidos por política"]];',
    'for(const [value,name] of summary){const card=el("div",undefined,"card");card.append(el("strong",value),el("span",name));$("cards").append(card);}',
    'function choices(id,values){for(const value of values.sort()){const opt=el("option",label(value));opt.value=value;$(id).append(opt);}}',
    'choices("type",[...new Set(payload.moves.map(m=>m.type).filter(Boolean))]);',
    'choices("action",[...new Set(payload.moves.map(m=>m.action).filter(Boolean))]);',
    'choices("evidence",[...new Set(payload.moves.map(m=>m.evidence).filter(Boolean))]);',
    'function cell(row,node){const t=document.createElement("td");t.append(node);row.append(t);}',
    'function rowFor(m){const row=document.createElement("tr");',
    'const title=el("strong",m.name);if(m.protected)title.append(el("span"," protegido","tag protected"));cell(row,title);',
    'const category=el("span",String(m.type||"—").toUpperCase());category.append(el("span",m.family,"small"));cell(row,category);',
    'cell(row,el("span",label(m.action),"tag"+(m.protected?" protected":"")));',
    'cell(row,el("span",m.native||"não consta desta lista"));',
    'cell(row,el("span",label(m.evidence),"tag"+(m.evidence==="aggregate-low-confidence"?" low":"")));',
    'const detail=document.createElement("details");detail.append(el("summary",m.identifiers.length+" pistas"));detail.append(el("div",m.identifiers.join(" · "),"small"));cell(row,detail);return row;}',
    'function render(){const q=$("query").value.normalize("NFKD").toLowerCase(),type=$("type").value,action=$("action").value,evidence=$("evidence").value;',
    'const filtered=payload.moves.filter(m=>(!type||m.type===type)&&(!action||m.action===action)&&(!evidence||m.evidence===evidence)&&(!q||[m.name,m.type,m.family,...m.identifiers].join(" ").normalize("NFKD").toLowerCase().includes(q)));',
    'const root=$("moves");root.replaceChildren();const fragment=document.createDocumentFragment();',
    'for(const m of filtered.slice(0,150))fragment.append(rowFor(m));root.append(fragment);',
    '$("count").textContent=filtered.length+" de 283 golpes"+(filtered.length>150?" · exibindo os primeiros 150; refine os filtros":"");}',
    'for(const id of ["query","type","action","evidence"])$(id).addEventListener(id==="query"?"input":"change",render);',
    'render();',
    '})();',
    '</script></body></html>',
  ];
  return markup.join('\n');
}
